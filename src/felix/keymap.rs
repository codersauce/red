fn cmd(command: Command) -> KeyNode {
    KeyNode::Command(command)
}

pub fn motion_for(command: Command) -> Option<Motion> {
    let word = |forward, end, long| Some(Motion::Word(WordMotion { forward, end, long }));
    Some(match command {
        Command::MoveCharLeft => Motion::CharLeft,
        Command::MoveCharRight => Motion::CharRight,
        Command::MoveLineUp => Motion::LineUp,
        Command::MoveLineDown => Motion::LineDown,
        Command::MoveNextWordStart => return word(true, false, false),
        Command::MovePrevWordStart => return word(false, false, false),
        Command::MoveNextWordEnd => return word(true, true, false),
        Command::MovePrevWordEnd => return word(false, true, false),
        Command::MoveNextLongWordStart => return word(true, false, true),
        Command::MovePrevLongWordStart => return word(false, false, true),
        Command::MoveNextLongWordEnd => return word(true, true, true),
        Command::MovePrevLongWordEnd => return word(false, true, true),
        Command::GotoLineStart => Motion::LineStart,
        Command::GotoLineEnd => Motion::LineEnd,
        Command::GotoFirstNonwhitespace => Motion::FirstNonBlank,
        Command::GotoFileStart => Motion::FileStart,
        Command::GotoLastLine => Motion::LastLine,
        Command::GotoLine => Motion::GotoLine(None),
        Command::FindNextChar => Motion::Find(FindKind::Next),
        Command::FindPrevChar => Motion::Find(FindKind::Prev),
        Command::TillNextChar => Motion::Find(FindKind::TillNext),
        Command::TillPrevChar => Motion::Find(FindKind::TillPrev),
        _ => return None,
    })
}

/// Select mode extends motions. A few commands stay replacements.
pub fn extend_command(command: Command, select_mode: bool) -> bool {
    select_mode && motion_for(command).is_some()
}
